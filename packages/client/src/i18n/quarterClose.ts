/** « de X » ou « d’X », avec la même règle d'élision que le journal (§9). */
const de = (name: string): string => (startsWithVowelSound(String(name)) ? `d’${name}` : `de ${name}`);

/** « lot » ou « lots » d'après le nombre affiché : en français, singulier sous 2 (« 1,5 lot »). */
export function frLots(n: number): string {
  return Math.abs(n) < 2 ? 'lot' : 'lots';
}

/** En anglais, singulier pour exactement 1 (« 1 lot », « 0 lots », « 1.5 lots »). */
export function enLots(n: number): string {
  return Math.abs(n) === 1 ? 'lot' : 'lots';
}

